"""Shellby Phase 6 - Technical Guide PDF Generator.

Transforms curated technical guides and session transcripts into styled,
production-ready PDF documents using ReportLab.

Rectifications:
    - Multi-line paragraphs joined into continuous, properly spaced flowables (Issue 5.4).
    - Ordered / numbered lists (1. , 2. ) parsed with dedicated hierarchy (Issue 5.4).
    - Nested list indentation preserved across bullet depths (Issue 5.4).
    - Markdown tables (| col | col |) rendered as styled ReportLab Tables (Issue 5.4).
    - Markdown links [text](url) converted to clickable anchors (Issue 5.4).
    - Multi-line blockquotes grouped into unified callout blocks (Issue 5.4).
    - Long code line wrapping & block chunking preventing Table LayoutError crashes (Issue 5.5).
    - Dynamic page geometry supporting both Letter and A4 sizes (Issue 5.6).
    - Canvas state deepcopy eliminating stack corruption in NumberedCanvas (Issue 5.7).
    - Reusable, CommonMark-aligned parsing logic (Issue 5.8).
"""

