# ---------------------------------------------------------------------------
# Numbered Canvas with Safe State Handling (Issues 5.6 & 5.7)
# ---------------------------------------------------------------------------

class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas with safe state stack cloning and dynamic page geometry."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict] = []

    def showPage(self):
        # Deep copy mutable canvas state to prevent canvas stack corruption (Issue 5.7)
        state = dict(self.__dict__)
        state["state_stack"] = copy.deepcopy(self.state_stack)
        state["_code"] = list(self._code)
        self._saved_page_states.append(state)
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#64748b"))

        # Dynamic geometry calculation (Issue 5.6)
        page_width, page_height = self._pagesize
        left_margin = 36
        right_margin = page_width - 36
        header_y = page_height - 38
        footer_y = 30
        rule_footer_y = 45

        # Top Header (pages 2+)
        if self._pageNumber > 1:
            self.drawString(left_margin, header_y, "Shellby Technical Guide")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(left_margin, header_y - 6, right_margin, header_y - 6)

        # Bottom Footer (all pages)
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.5)
        self.line(left_margin, rule_footer_y, right_margin, rule_footer_y)

        footer_text = "Generated by Shellby"
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawString(left_margin, footer_y, footer_text)
        self.drawRightString(right_margin, footer_y, page_str)

        self.restoreState()


