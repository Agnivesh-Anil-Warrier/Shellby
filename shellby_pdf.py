# ---------------------------------------------------------------------------
# Markdown Inline & Badge Formatter
# ---------------------------------------------------------------------------

def _clean_inline_markdown(text: str) -> str:
    """Escape XML and convert markdown inline styles (bold, italic, code, links)."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    # Markdown links: [text](url) -> <a href="url" color="#2563eb"><u>text</u></a> (Issue 5.4)
    text = re.sub(
        r"\[([^\]]+)\]\(([^)]+)\)",
        r'<a href="\2" color="#2563eb"><u>\1</u></a>',
        text,
    )

    # Bold: **text** -> <b>text</b>
    text = re.sub(r"\*\*(.*?)\*\*", r"<b>\1</b>", text)

    # Italic: *text* -> <i>text</i>
    text = re.sub(r"\*(.*?)\*", r"<i>\1</i>", text)

    # Inline code: `code` -> <font ...>code</font>
    text = re.sub(
        r"`(.*?)`",
        r'<font name="Courier" color="#1e293b" size="9"><b>\1</b></font>',
        text,
    )

    return text


def _format_header_badges(text: str) -> str:
    """Format category tags like [SETUP] or [BUILD] into styled colored badges."""
    badge_colors = {
        "SETUP": "#10b981",
        "DEPENDENCY": "#0284c7",
        "CONFIG": "#8b5cf6",
        "BUILD": "#f59e0b",
        "EXECUTION": "#2563eb",
        "VERIFICATION": "#059669",
        "CLEANUP": "#64748b",
    }

    def replace_badge(match):
        tag = match.group(1).upper()
        color = badge_colors.get(tag, "#3b82f6")
        return f' <font color="{color}"><b>[{tag}]</b></font>'

    return re.sub(r"\[([A-Za-z0-9_-]+)\]", replace_badge, text)


