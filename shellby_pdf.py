def render_markdown_to_pdf(
    md_content: str,
    output_path: Path,
    doc_title: str | None = None,
    page_size=letter,
) -> Path:
    """Convert Markdown string to a rendered PDF document supporting letter or A4."""
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    left_margin = 36
    right_margin = 36
    top_margin = 54
    bottom_margin = 54

    page_width, _page_height = page_size
    content_width = page_width - left_margin - right_margin

    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=page_size,
        leftMargin=left_margin,
        rightMargin=right_margin,
        topMargin=top_margin,
        bottomMargin=bottom_margin,
    )

    styles = _build_styles()
    flowables = parse_markdown_to_flowables(md_content, styles, content_width=content_width)

    doc.build(flowables, canvasmaker=NumberedCanvas)
    return output_path


def render_pdf_file(
    input_path: Path,
    output_path: Path,
    page_size=letter,
) -> Path:
    """Read a Markdown or blocks.json file and convert into a PDF document."""
    input_path = Path(input_path)
    if not input_path.exists():
        raise FileNotFoundError(f"Input file not found: {input_path}")

    content = input_path.read_text(encoding="utf-8")

    if input_path.suffix == ".json":
        try:
            import shellby_markdown
            content = shellby_markdown.render_markdown(input_path)
        except Exception:
            pass

    return render_markdown_to_pdf(content, output_path, page_size=page_size)


def main() -> None:
    if len(sys.argv) < 2:
        sys.exit(f"Usage: {sys.argv[0]} <input.md|blocks.json> [--out output.pdf] [--a4]")

    input_path = Path(sys.argv[1])
    out_path = input_path.with_suffix(".pdf")

    page_size = letter
    if "--a4" in sys.argv:
        page_size = A4

    if "--out" in sys.argv or "-o" in sys.argv:
        idx = sys.argv.index("--out") if "--out" in sys.argv else sys.argv.index("-o")
        out_path = Path(sys.argv[idx + 1])

    res = render_pdf_file(input_path, out_path, page_size=page_size)
    print(f"PDF guide successfully generated at: {res}")


if __name__ == "__main__":
    main()