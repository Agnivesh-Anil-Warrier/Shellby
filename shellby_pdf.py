# Markdown to Flowables Parser (Issues 5.4 & 5.5)
# ---------------------------------------------------------------------------

def _wrap_code_text(lines: list[str], max_len: int = 86) -> str:
    """Wrap long code lines so preformatted blocks do not overflow page width (Issue 5.5)."""
    wrapped: list[str] = []
    for line in lines:
        if len(line) <= max_len:
            wrapped.append(line)
        else:
            parts = textwrap.wrap(
                line,
                width=max_len,
                subsequent_indent="  ",
                break_long_words=True,
                break_on_hyphens=False,
            )
            wrapped.extend(parts)
    return "\n".join(wrapped)


def _render_code_table(code_str: str, styles: dict[str, ParagraphStyle], content_width: float) -> Table:
    """Create a styled table for a chunk of code."""
    p = Preformatted(code_str, styles["Code"])
    tbl = Table([[p]], colWidths=[content_width])
    tbl.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#cbd5e1")),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 7),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 7),
            ]
        )
    )
    return tbl


def parse_markdown_to_flowables(
    md_content: str,
    styles: dict[str, ParagraphStyle],
    content_width: float = 540.0,
) -> list:
    """Parse markdown into ReportLab flowables, addressing all Issue 5.4 & 5.5 bugs."""
    flowables = []
    lines = md_content.splitlines()

    i = 0
    in_code_block = False
    code_lines: list[str] = []

    while i < len(lines):
        line = lines[i]

        # 1. Code block fence toggle
        if line.strip().startswith("```"):
            if not in_code_block:
                in_code_block = True
                code_lines = []
            else:
                in_code_block = False
                if code_lines:
                    # Wrap long lines preventing page edge overflow (Issue 5.5)
                    wrapped_code = _wrap_code_text(code_lines)
                    wrapped_lines = wrapped_code.splitlines()

                    # Chunk code blocks exceeding ~40 lines to avoid ReportLab Table LayoutError
                    chunk_size = 40
                    for c_idx in range(0, max(1, len(wrapped_lines)), chunk_size):
                        chunk_text = "\n".join(wrapped_lines[c_idx : c_idx + chunk_size])
                        if chunk_text:
                            tbl = _render_code_table(chunk_text, styles, content_width)
                            flowables.append(Spacer(1, 3))
                            flowables.append(tbl)
                            flowables.append(Spacer(1, 5))
            i += 1
            continue

        if in_code_block:
            code_lines.append(line)
            i += 1
            continue

        raw_line = line
        stripped = raw_line.strip()

        if not stripped:
            i += 1
            continue

        # 2. Horizontal Rule
        if stripped in ("---", "***", "___"):
            flowables.append(Spacer(1, 4))
            flowables.append(
                HRFlowable(
                    width="100%",
                    thickness=0.75,
                    color=colors.HexColor("#e2e8f0"),
                    spaceBefore=6,
                    spaceAfter=10,
                )
            )
            i += 1
            continue

        # 3. Headers (#, ##, ###)
        if stripped.startswith("# "):
            title_text = _clean_inline_markdown(stripped[2:])
            flowables.append(Paragraph(title_text, styles["Title"]))
            flowables.append(
                HRFlowable(
                    width="100%",
                    thickness=1.5,
                    color=colors.HexColor("#2563eb"),
                    spaceBefore=2,
                    spaceAfter=12,
                )
            )
            i += 1
            continue

        if stripped.startswith("## "):
            h2_text = _clean_inline_markdown(stripped[3:])
            h2_html = _format_header_badges(h2_text)
            flowables.append(Paragraph(h2_html, styles["H2"]))
            i += 1
            continue

        if stripped.startswith("### "):
            h3_text = _clean_inline_markdown(stripped[4:])
            flowables.append(Paragraph(h3_text, styles["H3"]))
            i += 1
            continue

        # 4. Multi-line Blockquotes & Callouts (Issue 5.4)
        if stripped.startswith("> ") or stripped.startswith("*Expected Output:*"):
            callout_paras = []
            while i < len(lines):
                cur_stripped = lines[i].strip()
                if cur_stripped.startswith("> "):
                    q_text = _clean_inline_markdown(cur_stripped[2:].strip())
                    callout_paras.append(Paragraph(q_text, styles["Callout"]))
                    i += 1
                elif cur_stripped.startswith("*Expected Output:*"):
                    q_text = _clean_inline_markdown(cur_stripped)
                    callout_paras.append(Paragraph(q_text, styles["Callout"]))
                    i += 1
                else:
                    break

            tbl_content = [[p] for p in callout_paras]
            tbl = Table(tbl_content, colWidths=[content_width])
            tbl.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
                        ("LINELEFT", (0, 0), (0, -1), 3, colors.HexColor("#3b82f6")),
                        ("LEFTPADDING", (0, 0), (-1, -1), 10),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                        ("TOPPADDING", (0, 0), (-1, -1), 6),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                    ]
                )
            )
            flowables.append(Spacer(1, 4))
            flowables.append(tbl)
            flowables.append(Spacer(1, 6))
            continue

        # 5. Markdown Tables (| col | col |) (Issue 5.4)
        if stripped.startswith("|") and stripped.endswith("|") and i + 1 < len(lines):
            next_stripped = lines[i + 1].strip()
            if re.match(r"^\|(?:\s*:?-+:?\s*\|)+$", next_stripped):
                # Header row
                header_cells = [c.strip() for c in stripped.strip("|").split("|")]
                i += 2  # skip header and delimiter

                table_data = [
                    [Paragraph(_clean_inline_markdown(c), styles["TableHead"]) for c in header_cells]
                ]

                while i < len(lines) and lines[i].strip().startswith("|"):
                    row_cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
                    table_data.append(
                        [Paragraph(_clean_inline_markdown(c), styles["TableCell"]) for c in row_cells]
                    )
                    i += 1

                col_w = content_width / max(1, len(header_cells))
                tbl = Table(table_data, colWidths=[col_w] * len(header_cells))
                tbl.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
                            ("GRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
                            ("TOPPADDING", (0, 0), (-1, -1), 5),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                            ("LEFTPADDING", (0, 0), (-1, -1), 6),
                            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                        ]
                    )
                )
                flowables.append(Spacer(1, 4))
                flowables.append(tbl)
                flowables.append(Spacer(1, 8))
                continue

        # 6. Ordered Lists (1. , 2. ) (Issue 5.4)
        ordered_match = re.match(r"^(\d+)\.\s+(.*)$", stripped)
        if ordered_match:
            num = ordered_match.group(1)
            item_text = _clean_inline_markdown(ordered_match.group(2))
            flowables.append(Paragraph(f"<b>{num}.</b> {item_text}", styles["Ordered"]))
            i += 1
            continue

        # 7. Unordered / Nested Bullet Lists (- , * ) (Issue 5.4)
        bullet_match = re.match(r"^(\s*)[-*+]\s+(.*)$", raw_line)
        if bullet_match:
            indent_spaces = len(bullet_match.group(1))
            depth = indent_spaces // 2
            bullet_char = "•" if depth == 0 else "◦"
            item_text = _clean_inline_markdown(bullet_match.group(2))

            # Apply indentation
            item_style = styles["Bullet"]
            if depth > 0:
                item_style = ParagraphStyle(
                    f"BulletDepth{depth}",
                    parent=styles["Bullet"],
                    leftIndent=15 + (depth * 14),
                )

            flowables.append(Paragraph(f"{bullet_char} {item_text}", item_style))
            i += 1
            continue

        # 8. Multi-line Paragraphs (joined continuous text) (Issue 5.4)
        para_lines = [stripped]
        i += 1
        while i < len(lines):
            next_line = lines[i]
            next_stripped = next_line.strip()
            # Stop if empty line, code fence, header, list, table, or callout
            if (
                not next_stripped
                or next_stripped.startswith("```")
                or next_stripped.startswith("#")
                or next_stripped.startswith("- ")
                or next_stripped.startswith("* ")
                or next_stripped.startswith("> ")
                or re.match(r"^\d+\.\s+", next_stripped)
                or (next_stripped.startswith("|") and next_stripped.endswith("|"))
                or next_stripped in ("---", "***", "___")
            ):
                break
            para_lines.append(next_stripped)
            i += 1

        continuous_text = " ".join(para_lines)
        clean_text = _clean_inline_markdown(continuous_text)
        flowables.append(Paragraph(clean_text, styles["Body"]))

    return flowables


