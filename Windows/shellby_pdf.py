# ---------------------------------------------------------------------------
# Inline Markdown Converter
# ---------------------------------------------------------------------------

_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
_BOLD_RE = re.compile(r"\*\*([^*]+)\*\*")
_ITALIC_RE = re.compile(r"\*([^*]+)\*")
_CODE_RE = re.compile(r"`([^`]+)`")


def _inline_to_reportlab(text: str) -> str:
    """Convert CommonMark inline formatting into ReportLab HTML tags."""
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    # Links: [text](url) -> <link href="url" color="#2563eb"><u>text</u></link>
    def link_sub(m):
        label, url = m.group(1), m.group(2)
        return f'<link href="{url}" color="#2563eb"><u>{label}</u></link>'
    text = _LINK_RE.sub(link_sub, text)

    # Bold: **text** -> <b>text</b>
    text = _BOLD_RE.sub(r"<b>\1</b>", text)

    # Italic: *text* -> <i>\1</i>
    text = _ITALIC_RE.sub(r"<i>\1</i>", text)

    # Inline Code: `text` -> <font face="Courier" color="#0f172a">\1</font>
    text = _CODE_RE.sub(r'<font face="Courier" color="#0f172a">\1</font>', text)

    return text


# ---------------------------------------------------------------------------
# Flowable Builders
# ---------------------------------------------------------------------------

def _build_code_card(
    code_text: str,
    lang: str,
    styles: dict[str, ParagraphStyle],
    available_width: float,
) -> list:
    """Render a styled code card with line wrapping and pagination chunks."""
    flowables = []

    # Category or Language Header Badge
    lang_display = lang.upper() if lang else "CMD"
    badge_p = Paragraph(
        f'<font color="#64748b"><b>{lang_display}</b></font>',
        styles["callout"],
    )

    # Wrap code lines to prevent overflow
    max_chars_per_line = max(40, int(available_width / 5.2))
    wrapped_lines = []
    for line in code_text.splitlines():
        if len(line) > max_chars_per_line:
            wrapped_lines.extend(textwrap.wrap(line, width=max_chars_per_line, subsequent_indent="  "))
        else:
            wrapped_lines.append(line)

    chunk_size = 45
    line_chunks = [
        wrapped_lines[i:i + chunk_size]
        for i in range(0, max(1, len(wrapped_lines)), chunk_size)
    ]

    for idx, chunk in enumerate(line_chunks):
        chunk_text = "\n".join(chunk)
        pre = Preformatted(chunk_text, styles["code"])

        card_data = [[badge_p], [pre]] if idx == 0 else [[pre]]
        t = Table(card_data, colWidths=[available_width])
        t.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
                ("BOX", (0, 0), (-1, -1), 0.75, colors.HexColor("#e2e8f0")),
                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ])
        )
        flowables.append(t)
        if idx < len(line_chunks) - 1:
            flowables.append(Spacer(1, 4))

    flowables.append(Spacer(1, 6))
    return flowables


def _build_callout_box(
    quote_text: str,
    styles: dict[str, ParagraphStyle],
    available_width: float,
) -> Table:
    """Render a blockquote as a styled callout box with a colored left border."""
    rl_text = _inline_to_reportlab(quote_text)
    p = Paragraph(rl_text, styles["callout"])

    t = Table([[p]], colWidths=[available_width])
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f1f5f9")),
            ("LINEBEFORE", (0, 0), (0, -1), 3.0, colors.HexColor("#6366f1")),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("TOPPADDING", (0, 0), (-1, -1), 6),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ])
    )
    return t


def _build_markdown_table(
    table_lines: list[str],
    styles: dict[str, ParagraphStyle],
    available_width: float,
) -> Table | None:
    """Parse Markdown table into a styled ReportLab Table."""
    rows = []
    for line in table_lines:
        line = line.strip()
        if not line or re.match(r"^\|?[\s\-:|]+\|?$", line):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        rows.append(cells)

    if not rows:
        return None

    num_cols = max(len(r) for r in rows)
    col_width = available_width / num_cols

    table_data = []
    for row_idx, r in enumerate(rows):
        padded_row = r + [""] * (num_cols - len(r))
        style = styles["th"] if row_idx == 0 else styles["td"]
        table_data.append([
            Paragraph(_inline_to_reportlab(cell), style)
            for cell in padded_row
        ])

    t = Table(table_data, colWidths=[col_width] * num_cols)
    t.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
            ("BOTTOMPADDING", (0, 0), (-1, 0), 6),
            ("TOPPADDING", (0, 0), (-1, 0), 6),
            ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("TOPPADDING", (0, 1), (-1, -1), 5),
            ("BOTTOMPADDING", (0, 1), (-1, -1), 5),
        ])
    )
    return t


# ---------------------------------------------------------------------------
# Document Parsing & PDF Generation
# ---------------------------------------------------------------------------

def parse_markdown_to_flowables(
    md_text: str,
    available_width: float,
    page_size: tuple[float, float] = letter,
) -> list:
    """Parse CommonMark text into a list of styled ReportLab flowables."""
    styles = _build_styles()
    flowables = []

    lines = md_text.splitlines()
    idx = 0
    total = len(lines)

    while idx < total:
        line = lines[idx]
        stripped = line.strip()

        # 1. Blank line
        if not stripped:
            idx += 1
            continue

        # 2. Horizontal rule: --- or ***
        if re.match(r"^(?:---+|\*\*\*+|___+)$", stripped):
            flowables.append(Spacer(1, 4))
            flowables.append(HRFlowable(width="100%", thickness=0.5, color=colors.HexColor("#cbd5e1"), spaceAfter=8))
            idx += 1
            continue

        # 3. Fenced Code Block: ```lang ... ```
        if stripped.startswith("```"):
            lang = stripped.lstrip("`").strip()
            code_lines = []
            idx += 1
            while idx < total and not lines[idx].strip().startswith("```"):
                code_lines.append(lines[idx])
                idx += 1
            if idx < total:
                idx += 1  # consume closing ```
            card_flowables = _build_code_card(
                code_text="\n".join(code_lines),
                lang=lang,
                styles=styles,
                available_width=available_width,
            )
            flowables.extend(card_flowables)
            continue

        # 4. Markdown Table: starts with |
        if stripped.startswith("|"):
            tbl_lines = []
            while idx < total and lines[idx].strip().startswith("|"):
                tbl_lines.append(lines[idx])
                idx += 1
            tbl = _build_markdown_table(tbl_lines, styles, available_width)
            if tbl:
                flowables.append(Spacer(1, 4))
                flowables.append(tbl)
                flowables.append(Spacer(1, 8))
            continue

        # 5. Blockquote: > ...
        if stripped.startswith(">"):
            quote_lines = []
            while idx < total and lines[idx].strip().startswith(">"):
                quote_lines.append(lines[idx].strip().lstrip(">").strip())
                idx += 1
            callout = _build_callout_box(" ".join(quote_lines), styles, available_width)
            flowables.append(Spacer(1, 4))
            flowables.append(callout)
            flowables.append(Spacer(1, 6))
            continue

        # 6. Headings
        if stripped.startswith("#"):
            m = re.match(r"^(#{1,6})\s+(.*)$", stripped)
            if m:
                level = len(m.group(1))
                h_text = _inline_to_reportlab(m.group(2).strip())
                if level == 1:
                    flowables.append(Paragraph(h_text, styles["title"]))
                    flowables.append(HRFlowable(width="100%", thickness=1.0, color=colors.HexColor("#6366f1"), spaceAfter=10))
                elif level == 2:
                    flowables.append(Paragraph(h_text, styles["h1"]))
                elif level == 3:
                    flowables.append(Paragraph(h_text, styles["h2"]))
                else:
                    flowables.append(Paragraph(h_text, styles["h3"]))
                idx += 1
                continue

        # 7. Unordered Bullet List: - item or * item
        if re.match(r"^[-*]\s+", stripped):
            bullet_text = re.sub(r"^[-*]\s+", "", stripped)
            rl_text = _inline_to_reportlab(bullet_text)
            flowables.append(Paragraph(f"&bull; {rl_text}", styles["bullet"]))
            idx += 1
            continue

        # 8. Ordered Numbered List: 1. item
        m_num = re.match(r"^(\d+)\.\s+(.*)$", stripped)
        if m_num:
            num = m_num.group(1)
            num_text = _inline_to_reportlab(m_num.group(2))
            flowables.append(Paragraph(f"<b>{num}.</b> {num_text}", styles["bullet"]))
            idx += 1
            continue

        # 9. Paragraph: join contiguous lines into a continuous block
        para_lines = [stripped]
        idx += 1
        while idx < total:
            next_l = lines[idx].strip()
            if not next_l or next_l.startswith(("#", "-", "*", ">", "```", "|")):
                break
            if re.match(r"^\d+\.\s+", next_l):
                break
            para_lines.append(next_l)
            idx += 1

        p_text = _inline_to_reportlab(" ".join(para_lines))
        flowables.append(Paragraph(p_text, styles["body"]))

    return flowables


def render_markdown_to_pdf(
    md_content: str,
    output_path: Path,
    page_size_name: str = "letter",
) -> Path:
    """Generate a styled PDF document from Markdown content on Windows."""
    page_size = letter if page_size_name.lower() == "letter" else A4
    page_width, page_height = page_size

    margin = 36  # 0.5 inch
    available_width = page_width - (2 * margin)

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=page_size,
        leftMargin=margin,
        rightMargin=margin,
        topMargin=48,
        bottomMargin=48,
    )

    flowables = parse_markdown_to_flowables(
        md_text=md_content,
        available_width=available_width,
        page_size=page_size,
    )

    doc.build(flowables, canvasmaker=NumberedCanvas)
    return output_path


if __name__ == "__main__":
    if len(sys.argv) < 3:
        sys.exit("Usage: python shellby_pdf.py <input.md> <output.pdf>")
    in_p = Path(sys.argv[1])
    out_p = Path(sys.argv[2])
    render_markdown_to_pdf(in_p.read_text(encoding="utf-8"), out_p)
    print(f"Generated PDF: {out_p}")
